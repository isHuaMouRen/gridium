package me.hua.gridium.core;

/** Horizontal placement of a framework element within its allocated layout area. */
public enum HorizontalAlignment {
	/** Positions the element at the left edge and preserves its desired width. */
	LEFT,
	/** Centers the element and preserves its desired width. */
	CENTER,
	/** Positions the element at the right edge and preserves its desired width. */
	RIGHT,
	/** Stretches the element to fill the allocated width. */
	STRETCH
}
