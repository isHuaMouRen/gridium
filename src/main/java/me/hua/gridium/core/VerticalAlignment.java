package me.hua.gridium.core;

/** Vertical placement of a framework element within its allocated layout area. */
public enum VerticalAlignment {
	/** Positions the element at the top edge and preserves its desired height. */
	TOP,
	/** Centers the element and preserves its desired height. */
	CENTER,
	/** Positions the element at the bottom edge and preserves its desired height. */
	BOTTOM,
	/** Stretches the element to fill the allocated height. */
	STRETCH
}
